"""Prepare distinct Collector YAMLs without changing shipped service configuration."""

from __future__ import annotations

import argparse
import os
from pathlib import Path
from typing import Any

import yaml


def _service(path: Path) -> dict[str, Any]:
    if not path.is_file() or path.is_symlink():
        raise ValueError(f"missing or symlinked Collector service config: {path}")
    loaded = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(loaded, dict) or loaded.get("schema_version") != 1:
        raise ValueError(f"invalid Collector service config: {path}")
    if not isinstance(loaded.get("messaging"), dict):
        raise ValueError("Collector messaging section must be a mapping")
    return loaded


def _create(path: Path, document: dict[str, Any]) -> None:
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as stream:
        stream.write(
            "# Generated by deploy/prepare_collectors.py; deployment-specific.\n"
            "# Configure messaging.servers and config_sources before service start.\n"
        )
        yaml.safe_dump(document, stream, sort_keys=False, allow_unicode=True)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--source", default="collector.yaml")
    args = parser.parse_args(argv)
    try:
        root = args.root.resolve(strict=True)
        name = Path(args.source)
        if name.name != args.source or not args.source.endswith(".yaml"):
            raise ValueError("source must be a filename under configs/services")
        parent = root / "configs" / "services"
        source = _service(parent / name)
        targets = {
            "realtime": parent / "collector-realtime.yaml",
            "reliable": parent / "collector-reliable.yaml",
        }
        if any(p.exists() for p in targets.values()):
            raise ValueError("Collector variants already exist; refusing overwrite")
        # 两份配置必须成对出现；失败时只删除本次通过 O_EXCL 新建的文件。
        created: list[Path] = []
        completed = False
        try:
            for delivery, path in targets.items():
                body = dict(source)
                body["messaging"] = {**source["messaging"], "delivery": delivery}
                _create(path, body)
                created.append(path)
                print(f"{delivery}: {path}")
            completed = True
        finally:
            if not completed:
                for path in created:
                    path.unlink(missing_ok=True)
        return 0
    except (OSError, ValueError, yaml.YAMLError) as exc:
        parser.exit(2, f"Collector deployment preparation failed: {exc}\n")


if __name__ == "__main__":
    raise SystemExit(main())
